//! The messages between the kernel (`sim-node`) and a firmware node's HAL (`ariel-os-sim`
//! on the Ariel fork), and how they travel.
//!
//! The schema is `schema/node.cddl` (D19); its types are generated into [`generated`] and
//! re-exported here. One message is one `SOCK_SEQPACKET` packet, JSON-encoded through
//! serde, with byte strings as base64url text (`docs/m8.md` finding 1). The sockets are
//! opened by each side, so this crate carries only the types, the framing and the
//! version.

#[allow(
    missing_docs,
    dead_code,
    non_snake_case,
    clippy::all,
    clippy::pedantic,
    reason = "generated by cddlc from schema/node.cddl"
)]
pub mod generated;

use std::fmt;

use serde::Serialize;
use serde::de::DeserializeOwned;

pub use generated::{
    Advance, Edge, Flash, FlashOp, Hello, I2c, I2cOp, I2cOpKind, Idle, KernelMessage, NodeMessage,
    PinConfig, PinConfigDir, PinConfigPull, PinSet, Reply, Shutdown, Spi, SpiOp, SpiOpKind, Start,
};

/// The protocol version, `hello.version`. The kernel refuses a node built against another.
pub const VERSION: u64 = generated::HelloVersion::VALUE;

/// The largest encoded message. A SEQPACKET packet this size fits the default socket
/// buffer.
pub const MAX_MESSAGE: usize = 64 * 1024;

/// The most data one bus or flash operation carries. The HAL splits larger operations, so
/// a message stays under [`MAX_MESSAGE`]: 32 KiB is about 43 KiB as base64url.
pub const MAX_CHUNK: usize = 32 * 1024;

/// A message that can't be encoded or decoded.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum WireError {
    /// Serialization failed (a bug in the sender).
    Encode(String),
    /// The packet is not a valid message of the expected direction.
    Decode(String),
    /// The encoded message is this many bytes, over [`MAX_MESSAGE`].
    TooLarge(usize),
}

impl fmt::Display for WireError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Encode(e) => write!(f, "can't encode message: {e}"),
            Self::Decode(e) => write!(f, "can't decode message: {e}"),
            Self::TooLarge(n) => write!(f, "message of {n} bytes is over {MAX_MESSAGE}"),
        }
    }
}

impl std::error::Error for WireError {}

/// Encodes `msg` into `buf`, replacing its contents.
///
/// # Errors
/// [`WireError::Encode`] if serialization fails, [`WireError::TooLarge`] if the result is
/// over [`MAX_MESSAGE`].
pub fn encode<T: Serialize>(msg: &T, buf: &mut Vec<u8>) -> Result<(), WireError> {
    buf.clear();
    serde_json::to_writer(&mut *buf, msg).map_err(|e| WireError::Encode(e.to_string()))?;
    if buf.len() > MAX_MESSAGE {
        return Err(WireError::TooLarge(buf.len()));
    }
    Ok(())
}

/// Decodes one packet.
///
/// # Errors
/// [`WireError::TooLarge`] for a packet over [`MAX_MESSAGE`], [`WireError::Decode`] for
/// anything that isn't a `T`.
pub fn decode<T: DeserializeOwned>(packet: &[u8]) -> Result<T, WireError> {
    if packet.len() > MAX_MESSAGE {
        return Err(WireError::TooLarge(packet.len()));
    }
    serde_json::from_slice(packet).map_err(|e| WireError::Decode(e.to_string()))
}
